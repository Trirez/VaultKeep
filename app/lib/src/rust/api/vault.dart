import 'dart:typed_data';

class EntryItem {
  const EntryItem({
    required this.id,
    required this.title,
    required this.username,
    required this.url,
    this.groupName,
  });

  final String id;
  final String title;
  final String username;
  final String url;
  final String? groupName;
}

class AttachmentItem {
  const AttachmentItem({
    required this.name,
    required this.size,
  });

  final String name;
  final int size;
}

class GroupItem {
  const GroupItem({
    required this.id,
    required this.name,
    required this.entryCount,
  });

  final String id;
  final String name;
  final int entryCount;
}

class TotpItem {
  const TotpItem({
    required this.code,
    required this.secondsRemaining,
    required this.period,
  });

  final String code;
  final int secondsRemaining;
  final int period;
}

class EntryDetails {
  const EntryDetails({
    required this.id,
    required this.title,
    required this.username,
    required this.url,
    required this.notes,
    this.groupId,
    this.groupName,
    this.otpUri,
    this.attachments = const [],
  });

  final String id;
  final String title;
  final String username;
  final String url;
  final String notes;
  final String? groupId;
  final String? groupName;
  final String? otpUri;
  final List<AttachmentItem> attachments;
}

class EntryData {
  const EntryData({
    required this.title,
    required this.username,
    required this.password,
    required this.url,
    required this.notes,
    this.groupId,
    this.otp,
  });

  final String title;
  final String username;
  final String password;
  final String url;
  final String notes;
  final String? groupId;
  final String? otp;
}

